  assert.equal(await tags.nth(1).getAttribute('aria-pressed'),'true');
  assert.notEqual(await page.locator('#tagDetails').innerText(),firstTag);
  assert.equal(await tagList.evaluate(el=>getComputedStyle(el,'::-webkit-scrollbar').width),'14px');
  await page.keyboard.press('End');
  assert.equal(await tags.last().getAttribute('aria-pressed'),'true');
  assert.ok(await tagList.evaluate(el=>el.scrollTop>0));
  await page.locator('#inspectPage').evaluate(el=>{el.scrollTop=0;});
  const canvas=page.locator('#viewport canvas');
  const beforeOrbit=await canvas.screenshot();
  const plot=await canvas.boundingBox();
  await page.mouse.move(plot.x+plot.width/2,plot.y+plot.height/2);
  await page.mouse.down();
  await page.mouse.move(plot.x+plot.width/2+110,plot.y+plot.height/2+35,{steps:8});
  await page.mouse.up();
  assert.ok(!beforeOrbit.equals(await canvas.screenshot()),'Dragging rotates the gamut');
  await page.evaluate(bytes=>window.hostReply({type:'profile',slot:'comparison',name:'Comparison.icc',bytes}),bytes);
  await page.waitForFunction(()=>document.querySelector('#statistics').textContent.includes('comparison'));
  assert.match(await page.locator('#comparisonLegend').innerText(),/Comparison.icc.*X-ray/);
  await page.selectOption('#renderMode','points');await page.uncheck('#xray');await page.click('#reset');
